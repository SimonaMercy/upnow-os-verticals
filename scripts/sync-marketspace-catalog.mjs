#!/usr/bin/env node
/**
 * Sync the vertical / subcategory declarations from the MarketSpace repo into this app.
 *
 *   node scripts/sync-marketspace-catalog.mjs [path/to/upnow-marketspace]
 *
 * Source of truth: upnow-marketspace `data/listings.js` (a browser global script, no module
 * system). It is evaluated in a sandbox exactly as a browser would run it — including the
 * runtime removal of Mixed-use (2026-10-11) at the bottom of that file — and the serialisable
 * part of each declaration is written to `src/lib/catalog/marketspace.generated.ts`.
 *
 * Only declarations are copied. MarketSpace's generated demo listings (`UP.LISTINGS`) are
 * deliberately NOT exported: this app shows real listings from the backend only.
 *
 * Images referenced by the declarations are copied to `public/marketspace/images/`.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, '..');
const msRoot = path.resolve(process.argv[2] ?? path.join(appRoot, '..', 'upnow-marketspace'));

const ctx = { console, document: { currentScript: null }, location: { pathname: '/', search: '' } };
ctx.window = ctx;
vm.createContext(ctx);
for (const f of ['js/core/paths.js', 'data/listings.js']) {
  vm.runInContext(fs.readFileSync(path.join(msRoot, f), 'utf8'), ctx, { filename: f });
}
const UP = ctx.UP;
if (!UP?.VORDER) throw new Error('UP global not found — is this the upnow-marketspace repo?');

const images = new Set();
const img = (p) => {
  const name = String(p).split('/').pop();
  images.add(name);
  return `/marketspace/images/${name}`;
};
const opt = (o) => (typeof o === 'object' && o !== null ? { v: String(o.v), l: String(o.l ?? o.v) } : { v: String(o), l: String(o) });

const verticals = UP.VORDER.map((vid) => {
  const v = UP.VERTICALS[vid];
  return {
    id: vid,
    label: v.label,
    icon: v.icon,
    blurb: v.blurb,
    offers: v.offers.map((o) => ({
      id: o.id,
      label: o.label,
      icon: o.icon ?? null,
      h1: o.h1 ?? o.label,
      short: o.short ?? null,
      sub: o.sub ?? null,
      basis: o.basis ?? null,
      action: o.action ?? null,
      flow: Array.isArray(o.flow) ? [...o.flow] : [],
      providerTypes: Array.isArray(o.org) ? [...o.org] : [],
      searchFields: Array.isArray(o.fields) ? [...o.fields] : [],
      permit: o.permit ?? null,
      flags: {
        lease: !!o.lease, perSqft: !!o.perSqft, people: !!o.people, coverage: !!o.coverage, late: !!o.late,
      },
      images: (Array.isArray(o.img) ? o.img : o.img ? [o.img] : []).map(img),
      leadForm: (o.form ?? []).map(([key, label, type, options]) => ({
        key, label, type, options: Array.isArray(options) ? options.map(String) : [],
      })),
      filters: (o.defs ?? []).map((d) => ({
        id: d.id,
        type: d.type,
        label: d.label,
        options: Array.isArray(d.options) ? d.options.map(opt) : [],
        unit: d.unit ?? null,
        required: !!d.required,
        many: !!d.many,
        field: d.field ?? null,
      })),
    })),
  };
});

const total = verticals.reduce((n, v) => n + v.offers.length, 0);
const header = `/* GENERATED by scripts/sync-marketspace-catalog.mjs from upnow-marketspace data/listings.js.
   Do not edit by hand — change MarketSpace, then re-run the script.
   ${verticals.length} verticals · ${total} subcategories (Mixed-use retired 2026-10-11). */
import type { MsVertical } from './types';

export const MS_VERTICALS: readonly MsVertical[] = `;
const out = path.join(appRoot, 'src/lib/catalog/marketspace.generated.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, header + JSON.stringify(verticals, null, 2) + ';\n');

const imgDir = path.join(appRoot, 'public/marketspace/images');
fs.mkdirSync(imgDir, { recursive: true });
for (const name of images) fs.copyFileSync(path.join(msRoot, 'assets/images', name), path.join(imgDir, name));

console.log(`wrote ${path.relative(appRoot, out)} — ${verticals.length} verticals, ${total} subcategories, ${images.size} images`);
